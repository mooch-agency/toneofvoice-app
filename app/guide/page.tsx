"use client"

import { Suspense, useCallback, useEffect, useRef, useState } from "react"
import { useRouter, useSearchParams } from "next/navigation"
import { Download, Loader2 } from "lucide-react"
import { track } from "@vercel/analytics"
import { Button } from "@/components/ui/button"
import { useAuth } from "@/components/AuthProvider"
import { useToast } from "@/hooks/use-toast"
import BreadcrumbSchema from "@/components/BreadcrumbSchema"
import { GuideLayout } from "@/components/GuideLayout"
import { GuideView } from "@/components/GuideView"
import { PostExportPrompt } from "@/components/PostExportPrompt"
import { AutoSaveGuide } from "@/components/dashboard/AutoSaveGuide"
import { useGuide, type BrandDetails } from "@/hooks/use-guide"
import { useAutosave, type AutosaveStatus } from "@/hooks/use-autosave"
import { hasUnlockPlaceholders } from "@/lib/guide-placeholders"
import { storePreview } from "@/lib/pending-draft"
import { MetaPixel } from "@/lib/meta-pixel"
import { isPaidTier } from "@/lib/tiers"
import { isPaidPlan, useCheckout } from "./_hooks/use-checkout"
import { useExpandGuide } from "./_hooks/use-expand-guide"
import { useGuideExport, type ExportFormat } from "./_hooks/use-guide-export"
import { usePreviewGeneration } from "./_hooks/use-preview-generation"
import { useSavedGuide, type LoadedGuide } from "./_hooks/use-saved-guide"
import { GenerationProgress, QuickLoad } from "./_components/GuideLoading"
import { ExpandBanner, GuideTip, PreviewPdfFooter } from "./_components/GuideBanners"
import { DownloadOptionsDialog, ExportGateDialog, PaymentDialog } from "./_components/GuideDialogs"

const SAVE_STATUS_LABEL: Partial<Record<AutosaveStatus, string>> = {
  pending: "Saving…",
  saving: "Saving…",
  saved: "Saved",
  error: "Not saved",
}

/**
 * /guide has two flows:
 * - preview (no guideId): the guide lives in localStorage; generated by /api/preview.
 * - saved (?guideId=…): loaded from the account and autosaved while editing.
 */
function GuideContent() {
  const router = useRouter()
  const searchParams = useSearchParams()
  const { user } = useAuth()
  const { toast } = useToast()

  const guideId = searchParams.get("guideId")
  const isPreviewFlow = !guideId
  const generate = searchParams.get("generate") === "preview"
  const subscribePlan = searchParams.get("subscribe")

  const [hasEdits, setHasEdits] = useState(false)
  const [paymentOpen, setPaymentOpen] = useState(false)
  const [exportGateOpen, setExportGateOpen] = useState(false)
  const [downloadOptionsOpen, setDownloadOptionsOpen] = useState(false)
  const [showPostExport, setShowPostExport] = useState(false)
  const postExportDismissedRef = useRef(false)
  const [expandedKey, setExpandedKey] = useState<number>()

  // Side effects of every user edit: the preview is kept in localStorage, saved guides are autosaved.
  const handleUserEdit = useCallback(
    (markdown: string) => {
      if (!isPreviewFlow) return setHasEdits(true)
      storePreview(markdown)
    },
    [isPreviewFlow]
  )

  const {
    content,
    setContent,
    updateContent,
    brandDetails,
    setBrandDetails,
    guideType,
    setGuideType,
    sections,
    activeSectionId,
    handleSectionSelect,
    viewMode,
    handleModeSwitch,
    subscriptionTier: tier,
    setSubscriptionTier,
    isUnlocked,
    scrollContainerRef,
    editorKey,
    setEditorKey,
    handleAddSection,
  } = useGuide({ fetchTier: isPreviewFlow, onContentChange: handleUserEdit })

  const onPreviewLoaded = useCallback(
    (markdown: string, brand: BrandDetails) => {
      setContent(markdown)
      setBrandDetails(brand)
    },
    [setContent, setBrandDetails]
  )
  const preview = usePreviewGeneration({ enabled: isPreviewFlow, generate, onLoad: onPreviewLoaded })

  const onSavedLoaded = useCallback(
    (guide: LoadedGuide) => {
      setContent(guide.content)
      setBrandDetails(guide.brandDetails)
      setGuideType(guide.planType)
      setSubscriptionTier(guide.tier)
      setHasEdits(false)
    },
    [setContent, setBrandDetails, setGuideType, setSubscriptionTier]
  )
  const saved = useSavedGuide(guideId, onSavedLoaded)

  // "Generate full guide" (up to ~2 min): the server only saves over the version it
  // generated from, so the guide is read-only and autosave is paused meanwhile.
  const onExpanded = useCallback(
    (markdown: string) => {
      setContent(markdown)
      setHasEdits(false) // the server already saved the expanded guide
      setEditorKey((k) => k + 1)
      setExpandedKey(Date.now())
    },
    [setContent, setEditorKey]
  )
  const { expanding, expand } = useExpandGuide({ guideId, onExpanded })
  const startExpand = () => {
    handleModeSwitch("preview")
    void expand()
  }

  const showSaveError = useCallback(
    () =>
      toast({
        title: "Save failed",
        description: "Your changes are still in the editor. We'll try again when you edit.",
        variant: "destructive",
      }),
    [toast]
  )
  const autosave = useAutosave({
    guideId,
    content,
    brandDetails,
    planType: guideType,
    enabled: !isPreviewFlow && hasEdits && !expanding,
    onError: showSaveError,
  })

  // One place for brand renames (editor H1): persisted in both flows.
  const handleBrandNameChange = (name: string) => {
    const next = { ...brandDetails, name }
    setBrandDetails(next)
    if (!isPreviewFlow) return setHasEdits(true)
    try {
      localStorage.setItem("brandDetails", JSON.stringify(next))
    } catch {
      // ignore
    }
  }

  // Checkout: after sign-up the user lands on /guide?subscribe=<plan>.
  const { processingPlan, startCheckout } = useCheckout()
  const subscribeTriggered = useRef(false)
  useEffect(() => {
    if (!isPaidPlan(subscribePlan) || !user || subscribeTriggered.current) return
    subscribeTriggered.current = true
    startCheckout(subscribePlan)
    router.replace("/guide", { scroll: false })
  }, [subscribePlan, user, startCheckout, router])

  const handleUpgrade = (action: string) => {
    if (!isPreviewFlow) return router.push("/dashboard/billing")
    track("Paywall Clicked", { location: "guide-page", action })
    setPaymentOpen(true)
  }

  const showExpandBanner = !isPreviewFlow && isPaidTier(tier) && hasUnlockPlaceholders(content)

  const brandName = brandDetails?.name || "Your Brand"
  const exporter = useGuideExport({
    content,
    brandName,
    websiteUrl: brandDetails?.websiteUrl,
    tier,
    preview: isPreviewFlow,
    onExported: () => {
      if (isPreviewFlow) return
      setDownloadOptionsOpen(false)
      if (!postExportDismissedRef.current) setShowPostExport(true)
    },
  })
  const runExport = (format: ExportFormat) => {
    if (format === "pdf") return exporter.exportPdf()
    if (format === "zip") return exporter.exportAll()
    return exporter.exportFile(format)
  }

  const handleDownloadClick = () => {
    if (!isPreviewFlow) return setDownloadOptionsOpen(true)
    if (!user) return setExportGateOpen(true)
    exporter.exportPdf()
  }

  // Fire ViewContent once when the preview guide is shown.
  const viewTrackedRef = useRef(false)
  useEffect(() => {
    if (!isPreviewFlow || !content || viewTrackedRef.current) return
    viewTrackedRef.current = true
    MetaPixel.viewContent("guide_preview")
  }, [isPreviewFlow, content])

  if (preview.loading || saved.loading || !content || sections.length === 0) {
    return isPreviewFlow && preview.generating ? (
      <GenerationProgress progress={preview.progress} step={preview.step} />
    ) : (
      <QuickLoad />
    )
  }

  // Signed-in starters see Ask AI too; the AI menu shows them an upgrade dialog.
  const showAI = !!user
  const saveLabel = isPreviewFlow ? undefined : SAVE_STATUS_LABEL[autosave.status]
  const headerContent = (
    <div className="flex items-center gap-3">
      {saveLabel && (
        <span className="hidden sm:inline text-xs text-gray-500" role="status" aria-live="polite">
          {saveLabel}
        </span>
      )}
      <Button onClick={handleDownloadClick} disabled={exporter.downloading !== null} variant="outline" size="sm" className="gap-2">
        {exporter.downloading ? <Loader2 className="h-3 w-3 animate-spin" /> : <Download className="h-3 w-3" />}
        Download
      </Button>
    </div>
  )

  return (
    <div className="animate-in fade-in duration-700">
      <AutoSaveGuide />
      <BreadcrumbSchema
        items={[
          { name: "Home", url: "https://toneofvoice.app" },
          { name: "Tone of Voice Guide", url: "https://toneofvoice.app/guide" },
        ]}
      />

      <GuideLayout
        sections={sections}
        activeSectionId={activeSectionId}
        onSectionChange={handleSectionSelect}
        subscriptionTier={tier}
        brandName={brandName}
        showDashboardLink={!!user}
        onUpgrade={() => handleUpgrade("unlock-style-guide")}
        viewMode={viewMode}
        // Read-only while generating: no edit toggle, no new sections.
        onModeSwitch={expanding ? undefined : handleModeSwitch}
        showEditTools
        headerContent={headerContent}
        onAddSection={expanding ? undefined : handleAddSection}
      >
        {showExpandBanner && (
          <ExpandBanner
            expanding={expanding}
            // Wait for pending edits to save so they cannot overwrite the generated sections.
            disabled={autosave.status === "pending" || autosave.status === "saving"}
            onExpand={startExpand}
          />
        )}
        {!isPreviewFlow && showPostExport && (
          <PostExportPrompt
            onDismiss={() => {
              postExportDismissedRef.current = true
              setShowPostExport(false)
            }}
            className="mb-3 shrink-0"
          />
        )}
        <GuideTip showAI={showAI} />
        <GuideView
          sections={sections}
          scrollContainerRef={scrollContainerRef}
          viewMode={expanding ? "preview" : viewMode}
          onContentChange={updateContent}
          brandName={brandName}
          onBrandNameChange={handleBrandNameChange}
          showPreviewBadge={isPreviewFlow && tier === "starter"}
          isUnlocked={isUnlocked}
          onUpgrade={() => handleUpgrade("unlock-section")}
          editorKey={editorKey}
          editorId={isPreviewFlow ? "preview-single-editor" : "saved-single-editor"}
          websiteUrl={brandDetails?.websiteUrl}
          subscriptionTier={tier}
          showAI={showAI}
          pdfFooter={isPreviewFlow && tier === "starter" ? <PreviewPdfFooter /> : null}
          contentClassName={expandedKey ? "animate-in fade-in slide-in-from-bottom-2 duration-500" : undefined}
          contentKey={expandedKey}
        />
      </GuideLayout>

      {isPreviewFlow ? (
        <>
          <ExportGateDialog open={exportGateOpen} onOpenChange={setExportGateOpen} />
          <PaymentDialog
            open={paymentOpen}
            onOpenChange={setPaymentOpen}
            processingPlan={processingPlan}
            onSubscribe={startCheckout}
          />
        </>
      ) : (
        <DownloadOptionsDialog
          open={downloadOptionsOpen}
          onOpenChange={setDownloadOptionsOpen}
          downloading={exporter.downloading}
          onExport={runExport}
        />
      )}
    </div>
  )
}

export default function GuidePage() {
  return (
    <Suspense
      fallback={
        <div className="flex min-h-screen items-center justify-center">
          <Loader2 className="h-8 w-8 animate-spin" />
        </div>
      }
    >
      <GuideContent />
    </Suspense>
  )
}
